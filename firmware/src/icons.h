// WMO code -> category. Single source of truth so icon and text can never disagree.
enum WeatherCategory {
  WC_SUNNY = 0, WC_CLEAR, WC_SLIGHTLY_CLOUDY, WC_CLOUD, WC_LIGHT_RAIN, WC_RAIN, WC_UNKNOWN
};

WeatherCategory classifyCode(int code) {
  if (code < 0) return WC_UNKNOWN;
  if (code <= 10) return WC_SUNNY;
  if (code <= 20) return WC_CLEAR;
  if (code <= 40) return WC_SLIGHTLY_CLOUDY;
  if (code <= 60) return WC_CLOUD;
  if (code <= 80) return WC_LIGHT_RAIN;
  if (code <= 99) return WC_RAIN;
  return WC_UNKNOWN;
}

const unsigned char* getBigIcon(int code) {
    switch (classifyCode(code)) {
      case WC_SUNNY:
      case WC_CLEAR:        return icon_sunny_32;
      case WC_SLIGHTLY_CLOUDY: return icon_slightly_cloudy_32;
      case WC_CLOUD:        return icon_cloudy_32;
      case WC_LIGHT_RAIN:   return icon_slight_rainy_32;
      default:              return icon_rainy_32;
    }
}

// Helper: Returns the 16x16 icon pointer
const unsigned char* getSmallIcon(int code) {
    switch (classifyCode(code)) {
      case WC_SUNNY:
      case WC_CLEAR:        return icon_sun_16;
      case WC_SLIGHTLY_CLOUDY: return icon_slight_cloudy_16;
      case WC_CLOUD:        return icon_cloudy_16;
      case WC_LIGHT_RAIN:   return icon_slight_rainy_16;
      default:              return icon_rainy_16;
    }
}
const char* getWeatherDescription(int code) {
    switch (classifyCode(code)) {
      case WC_SUNNY:        return "Sunny";
      case WC_CLEAR:        return "Clear";
      case WC_SLIGHTLY_CLOUDY: return "Slightly Cloudy";
      case WC_CLOUD:        return "Cloud";
      case WC_LIGHT_RAIN:   return "Light Rain";
      case WC_RAIN:         return "Rain";
      default:              return "N/A";
    }
}
