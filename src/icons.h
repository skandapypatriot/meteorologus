const unsigned char* getBigIcon(int code) {
    if (code >= 0 && code <= 35) return icon_sunny_32;
    if (code >= 36 && code <= 79) return icon_cloudy_32; // Includes cloud and snow/fog ranges
    if (code >= 50 && code <= 61 || code == 80) return icon_slight_rainy_32;
    return icon_rainy_32; // Default for heavy/stormy ranges (62-99)
}

// Helper: Returns the 16x16 icon pointer
const unsigned char* getSmallIcon(int code) {
    if (code >= 0 && code <= 35) return icon_sun_16;
    if (code >= 36 && code <= 79) return icon_cloudy_16;
    if (code >= 50 && code <= 61 || code == 80) return icon_slight_rainy_16;
    return icon_rainy_16; // Default for heavy/stormy
}
const char* getWeatherDescription(int code) {
    // Clear / Sunny
    if (code >= 0 && code <= 19) return "Clear";
    if (code >= 30 && code <= 35) return "Clear";
    
    // Clouds / Fog / Snow
    if (code >= 20 && code <= 29) return "Cloudy";
    if (code >= 36 && code <= 49) return "Cloudy";
    if (code >= 70 && code <= 79) return "Cloudy";
    
    // Light Rain
    if (code >= 50 && code <= 61) return "Light Rain";
    if (code == 80) return "Light Rain";
    
    // Harsh Rain / Thunderstorms
    if (code >= 62 && code <= 69) return "Heavy Rain";
    if (code >= 81 && code <= 99) return "Heavy Rain";
    
    return "Unknown";
}
